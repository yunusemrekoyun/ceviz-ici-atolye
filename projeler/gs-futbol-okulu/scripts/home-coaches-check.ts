import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import sharp from "sharp";
import { execFileSync } from "node:child_process";
import Database from "better-sqlite3";
import { sql } from "drizzle-orm";

const temporary = fs.mkdtempSync(path.join(os.tmpdir(), "gs-home-coaches-"));
process.env.DATABASE_PATH = path.join(temporary, "school.db");
async function main() {
  const { getDb } = await import("../lib/db");
  const { coachProfileSchema, coachPhotosDir, saveCoachProfile, loadPublishedCoaches, listCoachProfiles, readCoachPhoto, MAX_COACH_PHOTO_BYTES } = await import("../lib/coach-profiles");
  const values = { name: "Örnek Hoca", role: "Futbol Antrenörü", bio: "Oyun ve takım arkadaşlığı ile futbol eğitimi.", sortOrder: 20, isPublished: false, isDemo: true };
  const png = await sharp({ create: { width: 50, height: 60, channels: 4, background: { r: 180, g: 20, b: 60, alpha: 0.5 } } }).png().toBuffer();
  assert.equal(listCoachProfiles().length, 0);
  const draft = await saveCoachProfile(null, values, png);
  assert.ok(fs.existsSync(path.join(temporary, "coach-photos", draft.photoKey!)), "files live beside the configured database");
  assert.equal(loadPublishedCoaches().length, 0);
  assert.equal(readCoachPhoto(draft.photoKey!), null, "draft files cannot be read anonymously");
  const privatePhoto = readCoachPhoto(draft.photoKey!, true)!;
  assert.equal(privatePhoto.published, false);
  const raw = await sharp(privatePhoto.data).raw().toBuffer({ resolveWithObject: true });
  assert.equal(raw.info.channels, 4);
  assert.ok(raw.data[3]! > 100 && raw.data[3]! < 150, "upload conversion preserves transparency");
  const first = await saveCoachProfile(null, { ...values, name: "İlk Hoca", sortOrder: 10, isPublished: true }, png);
  await saveCoachProfile(draft.id, { ...values, isPublished: true });
  assert.deepEqual(loadPublishedCoaches().map(c => c.id), [String(first.id), String(draft.id)], "public profiles follow panel ordering");
  assert.equal(readCoachPhoto(draft.photoKey!)?.published, true);
  const replacement = await saveCoachProfile(draft.id, values, png);
  assert.notEqual(replacement.photoKey, draft.photoKey, "replacing a portrait changes its URL");
  assert.equal(readCoachPhoto(draft.photoKey!, true), null, "previous unreferenced images are never served");
  assert.ok(fs.existsSync(path.join(coachPhotosDir(), draft.photoKey!)), "previous bytes survive for database backups");
  assert.equal(loadPublishedCoaches().length, 1, "unpublishing removes the profile immediately");
  assert.equal(readCoachPhoto(replacement.photoKey!), null);
  assert.equal(readCoachPhoto("../../school.db", true), null);
  const countFiles = () => fs.readdirSync(coachPhotosDir()).length;
  const before = countFiles();
  await assert.rejects(saveCoachProfile(99999, values, png), /bulunamadı/);
  await assert.rejects(saveCoachProfile(null, { ...values, isPublished: true }), /fotoğraf ekleyin/);
  await assert.rejects(saveCoachProfile(null, values, Buffer.from('<svg xmlns="http://www.w3.org/2000/svg"></svg>')), /JPG, PNG/);
  await assert.rejects(saveCoachProfile(null, values, Buffer.alloc(MAX_COACH_PHOTO_BYTES + 1)), /10 MB/);
  await assert.rejects(saveCoachProfile(null, values, Buffer.from([0x89,0x50,0x4e,0x47,0x0d,0x0a,0x1a,0x0a,1,2,3,4,5])), /okunamadı/);
  assert.equal(countFiles(), before, "rejected inputs leave no files");
  getDb().run(sql`CREATE TRIGGER reject_test_profile BEFORE INSERT ON coach_profiles BEGIN SELECT RAISE(ABORT, 'test failure'); END`);
  await assert.rejects(saveCoachProfile(null, values, png), /test failure/);
  assert.equal(countFiles(), before, "failed database writes remove new uploads");
  assert.equal(coachProfileSchema.safeParse({ ...values, sortOrder: -1 }).success, false);
  assert.equal(coachProfileSchema.safeParse({ ...values, bio: " " }).success, false);
  fs.mkdirSync(path.join(temporary, "files"));
  fs.writeFileSync(path.join(temporary, "files", "test-receipt"), "test-only fixture");
  const backup = path.join(temporary, "backups");
  execFileSync(process.execPath, ["--import", "tsx", "scripts/backup.ts", backup], { cwd: process.cwd(), env: process.env });
  assert.equal(fs.readdirSync(path.join(backup, "coach-photos")).length, before, "backups include new and previous portraits");
  assert.equal(fs.readFileSync(path.join(backup, "files", "test-receipt"), "utf8"), "test-only fixture");
  const copy = new Database(path.join(backup, fs.readdirSync(backup).find(name => name.endsWith(".db"))!), { readonly: true });
  assert.equal((copy.prepare("SELECT COUNT(*) AS count FROM coach_profiles").get() as { count: number }).count, 2);
  copy.close();
  console.log("Coach migration, publication, ordering, alpha uploads, path validation, rollback and backup checks passed.");
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => fs.rmSync(temporary, { recursive: true, force: true }));
